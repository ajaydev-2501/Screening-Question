export const TOOLS_BY_KEY: ReadonlyMap<string, CatalogTool> = new Map(
  TOOL_CATALOG.map((tool) => [tool.key, tool] as const),
);

export function toolsInCategory(categoryKey: string): CatalogTool[] {
  return TOOL_CATALOG.filter((tool) => tool.categoryKey === categoryKey);
}

export function searchTools(query: string): CatalogTool[] {
  const normalized = query.trim().toLowerCase();
  if (normalized.length === 0) return [];
  return TOOL_CATALOG.filter((tool) => tool.name.toLowerCase().includes(normalized));
}

export function isKnownToolKey(key: string): boolean {
  return TOOLS_BY_KEY.has(key);
}
